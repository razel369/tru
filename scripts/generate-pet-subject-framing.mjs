import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { PNG } from "pngjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const motionRoot = path.join(root, "assets", "pet-motion");
const breedSource = fs.readFileSync(
  path.join(root, "src", "data", "pet-breeds.ts"),
  "utf8",
);
const exactSource = fs.readFileSync(
  path.join(root, "src", "features", "pet-motion", "exact-breed-packs.ts"),
  "utf8",
);
const outputPath = path.join(
  root,
  "src",
  "features",
  "pet-visuals",
  "subject-framing.generated.ts",
);

const slugify = (value) =>
  value
    .trim()
    .toLocaleLowerCase()
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

const speciesBySlug = new Map();
for (const [helper, species] of [
  ["dog", "dog"],
  ["cat", "cat"],
]) {
  const pattern = new RegExp(`${helper}\\(\"([^\"]+)\"`, "g");
  for (const match of breedSource.matchAll(pattern)) {
    speciesBySlug.set(slugify(match[1]), species);
  }
}

const exactKeyByFolder = new Map();
const exactPattern =
  /key:\s*"([^"]+)"[\s\S]*?idle:\s*require\("([^"]+idle-luna-style-v1\.png)"\)/g;
for (const match of exactSource.matchAll(exactPattern)) {
  exactKeyByFolder.set(path.basename(path.dirname(match[2])), match[1]);
}

const localKeyByFolder = new Map(
  [
    "dog:labrador-retriever",
    "dog:german-shepherd",
    "dog:siberian-husky",
    "dog:beagle",
    "dog:standard-poodle",
    "dog:pembroke-welsh-corgi",
    "dog:shiba-inu",
    "dog:samoyed",
    "cat:persian",
    "cat:ragdoll",
    "cat:bengal",
    "cat:scottish-fold",
    "cat:maine-coon",
    "cat:sphynx",
    "dog:chihuahua",
    "dog:french-bulldog",
    "dog:border-collie",
    "dog:great-dane",
    "dog:pomeranian",
    "cat:siamese",
    "dog:dachshund",
  ].map((value) => {
    const [species, ...slugParts] = value.split(":");
    const slug = slugParts.join(":");
    return [`breed-${slug}`, `breed:${species}:${slug}`];
  }),
);

const measure = (filePath) => {
  const png = PNG.sync.read(fs.readFileSync(filePath));
  let minX = png.width;
  let minY = png.height;
  let maxX = -1;
  let maxY = -1;
  for (let y = 0; y < png.height; y += 1) {
    for (let x = 0; x < png.width; x += 1) {
      const alpha = png.data[(y * png.width + x) * 4 + 3];
      if (alpha <= 12) continue;
      minX = Math.min(minX, x);
      minY = Math.min(minY, y);
      maxX = Math.max(maxX, x);
      maxY = Math.max(maxY, y);
    }
  }
  if (maxX < 0 || maxY < 0) {
    throw new Error(`No visible subject in ${filePath}`);
  }
  return {
    centerX: (minX + (maxX - minX + 1) / 2) / png.width,
    feetY: (maxY + 1) / png.height,
    subjectHeight: (maxY - minY + 1) / png.height,
    subjectWidth: (maxX - minX + 1) / png.width,
  };
};

const entries = new Map();
for (const directory of fs.readdirSync(motionRoot, { withFileTypes: true })) {
  if (!directory.isDirectory() || !directory.name.startsWith("breed-")) continue;
  const idlePath = path.join(
    motionRoot,
    directory.name,
    "idle-luna-style-v1.png",
  );
  if (!fs.existsSync(idlePath)) continue;
  const breedSlug = directory.name.replace(/^breed-/, "");
  const key =
    exactKeyByFolder.get(directory.name) ??
    localKeyByFolder.get(directory.name) ??
    (speciesBySlug.has(breedSlug)
      ? `breed:${speciesBySlug.get(breedSlug)}:${breedSlug}`
      : null);
  if (!key) {
    throw new Error(`Could not resolve a pet key for ${directory.name}`);
  }
  entries.set(key, measure(idlePath));
}

const lunaPath = path.join(motionRoot, "pet-luna", "idle-v2.png");
const miloPath = path.join(
  motionRoot,
  "pet-milo",
  "idle-luna-style-v1.png",
);
entries.set("pet:luna", measure(lunaPath));
entries.set("pet:milo", measure(miloPath));
entries.set("breed:dog:golden-retriever", measure(miloPath));

const format = (value) => Number(value.toFixed(6));
const body = [...entries.entries()]
  .sort(([left], [right]) => left.localeCompare(right))
  .map(
    ([key, value]) =>
      `  ${JSON.stringify(key)}: { centerX: ${format(value.centerX)}, feetY: ${format(value.feetY)}, subjectHeight: ${format(value.subjectHeight)}, subjectWidth: ${format(value.subjectWidth)} },`,
  )
  .join("\n");

const output = `// Generated by scripts/generate-pet-subject-framing.mjs.
// Do not hand-edit: these measurements keep every transparent pet canvas
// aligned to the same visible subject height and floor line.

export type PetSubjectFraming = {
  centerX: number;
  feetY: number;
  subjectHeight: number;
  subjectWidth: number;
};

const PET_SUBJECT_FRAMING: Readonly<Record<string, PetSubjectFraming>> = {
${body}
};

export const PET_SUBJECT_FRAMING_KEYS = Object.freeze(
  Object.keys(PET_SUBJECT_FRAMING),
);

const DEFAULT_FRAMING: PetSubjectFraming = {
  centerX: 0.5,
  feetY: 0.8,
  subjectHeight: 0.64,
  subjectWidth: 0.64,
};

export function resolvePetSubjectFraming(key: string): PetSubjectFraming {
  return PET_SUBJECT_FRAMING[key] ?? DEFAULT_FRAMING;
}
`;

fs.writeFileSync(outputPath, output, "utf8");
console.log(
  JSON.stringify({
    entries: entries.size,
    output: path.relative(root, outputPath),
  }),
);
